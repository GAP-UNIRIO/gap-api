CREATE TABLE orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    created_at timestamp with time zone NOT NULL,
    tipo_solicitacao varchar(255) NOT NULL,
    extra_data jsonb,
    graduation_event_id bigint
);

CREATE TABLE annexes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    url varchar(255) NOT NULL,
    name varchar(255) NOT NULL,
    content_type varchar(255)
);

CREATE TABLE approval_stages (
    id bigint NOT NULL,
    name varchar(255) NOT NULL,
    status varchar(255) NOT NULL,
    step_order integer NOT NULL,
    created_at timestamp with time zone NOT NULL,
    order_id bigint NOT NULL,
    user_id bigint,
    org_unit_id bigint,
    CONSTRAINT pk_approval_stages PRIMARY KEY (id)
);
CREATE SEQUENCE approval_stages_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE order_histories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    actor_id bigint,
    event_type varchar(50) NOT NULL,
    description text NOT NULL,
    created_at timestamp with time zone NOT NULL,
    payload jsonb
);

CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    order_id bigint NOT NULL,
    title varchar(100) NOT NULL,
    message varchar(255) NOT NULL,
    is_read boolean NOT NULL,
    action_url varchar(255) NOT NULL,
    created_at timestamp with time zone NOT NULL
);

CREATE TABLE graduation_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    event_date timestamp with time zone NOT NULL,
    course_id bigint NOT NULL
);

CREATE TABLE workflow_templates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_type varchar(255) NOT NULL,
    course_id bigint
);

CREATE TABLE workflow_steps (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id bigint NOT NULL,
    step_order integer NOT NULL,
    stage_type varchar(255) NOT NULL,
    responsible_unit_type varchar(255) NOT NULL,
    step_description varchar(255) NOT NULL,
    step_name varchar(255) NOT NULL
);

CREATE TABLE users_roles (
    user_id bigint NOT NULL,
    role_id bigint NOT NULL,
    CONSTRAINT pk_users_roles PRIMARY KEY (user_id, role_id)
);

